def compute_signal(df: pl.DataFrame) -> pl.DataFrame:
    """Evaluate causal alpha signal onto a sorted OHLCV DataFrame."""
    has_sym = bool(SYMBOL_COL and SYMBOL_COL in df.columns)
    sort_cols = [SYMBOL_COL, TIME_COL] if has_sym else [TIME_COL]
    work = df.sort(sort_cols)
