    mdd = float(eval_port.select(pa.max_drawdown("net_return")).item() or 0.0)
    tot_ret = float((1.0 + eval_port["net_return"]).product() - 1.0)
    summary = {{
        "net_sharpe": round(sr, 4),
        "total_return": round(tot_ret, 4),
        "max_drawdown": round(mdd, 4),
    }}
    return eval_port, summary


